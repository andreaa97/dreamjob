-- Per ogni cambiamento successivo crea un nuovo file (V2__..., V3__...).

CREATE TABLE jobs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(255) NOT NULL,
    company           VARCHAR(255) NOT NULL,
    location          VARCHAR(255),
    salary_min        BIGINT,
    salary_max        BIGINT,
    remote_from_italy BOOLEAN      NOT NULL
);

CREATE TABLE applications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status     VARCHAR(255) NOT NULL,
    applied_at DATE,
    job_id     BIGINT       NOT NULL,

    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),

    -- regola di business: una sola candidatura per job.
    -- Il database la garantisce anche se due richieste arrivano insieme.
    CONSTRAINT uq_applications_job UNIQUE (job_id)
);
